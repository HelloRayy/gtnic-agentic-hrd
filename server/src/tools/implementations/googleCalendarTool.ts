import { google } from 'googleapis';
import type { BaseTool, ToolParamDef } from '../registry.js';
import { googleAuthService } from '../../services/googleAuthService.js';

export interface ScheduleInterviewParams {
  candidateName: string;
  candidateEmail: string;
  jobTitle: string;
  startTime: string;
  durationMinutes?: number;
  interviewTopics?: string[];
  interviewerNotes?: string;
}

export interface ScheduleInterviewResult {
  status: 'SCHEDULED' | 'SIMULATED';
  eventId: string;
  eventLink?: string;
  meetLink?: string;
  startTime: string;
  endTime: string;
  summary: string;
  attendees: string[];
  isLive: boolean;
}

export class GoogleCalendarTool implements BaseTool<ScheduleInterviewParams, ScheduleInterviewResult> {
  public name = 'google_calendar_schedule';
  public description = 'Schedules a technical interview on Google Calendar with Google Meet and dossier anchors.';

  public parameterSchema: Record<string, ToolParamDef> = {
    candidateName: { type: 'string', required: true, description: 'Full name of candidate' },
    candidateEmail: { type: 'string', required: true, description: 'Candidate email address' },
    jobTitle: { type: 'string', required: true, description: 'Role applying for' },
    startTime: { type: 'string', required: true, description: 'Start time in ISO format (e.g. 2026-11-01T10:00:00Z)' },
    durationMinutes: { type: 'number', required: false, description: 'Duration in minutes (default: 45)' },
    interviewTopics: { type: 'object', required: false, description: 'Key technical topics generated by auditor' },
    interviewerNotes: { type: 'string', required: false, description: 'Optional private note for interviewer' },
  };

  public async execute(params: ScheduleInterviewParams): Promise<ScheduleInterviewResult> {
    const duration = params.durationMinutes || 45;
    const start = new Date(params.startTime);
    const end = new Date(start.getTime() + duration * 60 * 1000);
    const summary = `Technical Interview: ${params.candidateName} - ${params.jobTitle}`;

    const topicsList = Array.isArray(params.interviewTopics)
      ? params.interviewTopics.map((t) => `- ${t}`).join('\n')
      : 'Standard architecture and code verification review.';

    const description = [
      `Candidate: ${params.candidateName} (${params.candidateEmail})`,
      `Target Role: ${params.jobTitle}`,
      '',
      'Tailored Architecture & Verification Topics (Generated by TalentTrace AI):',
      topicsList,
      '',
      params.interviewerNotes ? `Interviewer Notes: ${params.interviewerNotes}` : '',
    ]
      .filter(Boolean)
      .join('\n');

    if (googleAuthService.isAuthenticated()) {
      try {
        const auth = googleAuthService.getClient();
        const calendar = google.calendar({ version: 'v3', auth });

        const response = await calendar.events.insert({
          calendarId: 'primary',
          conferenceDataVersion: 1,
          requestBody: {
            summary,
            description,
            start: { dateTime: start.toISOString() },
            end: { dateTime: end.toISOString() },
            attendees: [{ email: params.candidateEmail }],
            conferenceData: {
              createRequest: {
                requestId: `tt-${Date.now()}`,
                conferenceSolutionKey: { type: 'hangoutsMeet' },
              },
            },
          },
        });

        const event = response.data;
        const meetLink =
          event.conferenceData?.entryPoints?.find((e) => e.entryPointType === 'video')?.uri ||
          event.hangoutLink ||
          undefined;

        return {
          status: 'SCHEDULED',
          eventId: event.id || `evt-${Date.now()}`,
          eventLink: event.htmlLink || undefined,
          meetLink,
          startTime: start.toISOString(),
          endTime: end.toISOString(),
          summary,
          attendees: [params.candidateEmail],
          isLive: true,
        };
      } catch (err: unknown) {
        const message = err instanceof Error ? err.message : String(err);
        console.warn('[GoogleCalendarTool] Live API failed, falling back to simulated output:', message);
      }
    }

    // Simulated fallback when Google OAuth is not configured or in sandbox
    const mockId = `mock-cal-${Date.now().toString(36)}`;
    return {
      status: 'SIMULATED',
      eventId: mockId,
      eventLink: `https://calendar.google.com/calendar/r/eventedit?text=${encodeURIComponent(summary)}`,
      meetLink: `https://meet.google.com/gtnic-demo-${Date.now().toString(36).slice(-6)}`,
      startTime: start.toISOString(),
      endTime: end.toISOString(),
      summary,
      attendees: [params.candidateEmail],
      isLive: false,
    };
  }
}
